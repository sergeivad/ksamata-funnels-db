#!/usr/bin/env python3
"""Сопоставление источников. Ключ свой на каждом стыке.

Заказы ↔ база — по связке, ОБЯЗАТЕЛЬНО с поиском ближайшей воронки.
Замер 04.08: из десяти живых связок без воронки семь оказались ошибками
разметки в ГК (нет маркера типа, чужой маркер, задвоенная ось, нет оси
продукта), и только три — действительно новыми воронками. Без расстояния
до ближайшей все десять читаются одинаково, и разбор уходит не туда.

Таблица ↔ база — по лендингу, с падением на код и на «источник + продукт».
Ступень фиксируется в результате: совпадение по третьей означает, что
лендинг разошёлся или отсутствует, и это находка, а не деталь реализации.
"""

import re
from dataclasses import dataclass

import combo

AXIS_NAMES = combo.AXES + ('тип воронки',)

# Оси НЕ равны по силе опознания, и это решает, какая воронка «ближайшая».
# Продукт опознаёт воронку сильнее всего: две связки с разными продуктами —
# почти наверняка разные воронки. Маркер типа слабее всех: его сплошь и рядом
# просто не проставляют, и его отсутствие — самая частая ошибка разметки
# (454 заказа f69 на замере 04.08).
#
# Замер 04.08 без весов дал прямую ошибку: связку «ЖКТ / НИМБ / Яндекс / РСЯ /
# АВ Прямые» отнесло к f45 (продукт ЖИВО-суставы) вместо очевидной f8 (тот же
# ЖКТ, отличается только тип) — обе на расстоянии одной оси, а разрешал спор
# алфавит метки.
AXIS_WEIGHT = {
    'АВ Продукт': 5,
    'АВ Подрядчик': 4,
    'АВ Канал': 3,
    'АВ Направление': 2,
    'тип воронки': 1,
}

# Расходиться может максимум ОДНА ось, пусть даже самая тяжёлая. Две — это
# уже другая воронка, а не ошибка разметки: «RedBananas / ТГ» (новый подрядчик
# на новом канале) подавался как «похоже на #18», хотя его просто нет в базе.
MAX_DIFF_WEIGHT = max(AXIS_WEIGHT.values())


def _code_num(label):
    """Числовая часть метки — для устойчивой сортировки.

    Без неё строки сравниваются лексикографически, и 'f45' оказывается
    «меньше» 'f8'.
    """
    digits = re.sub(r'\D', '', label)
    return int(digits) if digits else 0


@dataclass(frozen=True)
class Near:
    funnel: object
    distance: int
    diff: list


@dataclass(frozen=True)
class SheetMatch:
    """Итог сопоставления строки.

    `candidates` непуст ровно в одном случае — ступень 3 нашла НЕСКОЛЬКО
    воронок и отказалась выбирать. Отличать этот отказ от «кандидатов нет
    вовсе» обязательно: «не смогли выбрать из четырёх» и «такой воронки
    нет» — разные утверждения, и одинаково выглядеть они не должны.
    """
    funnel: object
    tier: str
    candidates: tuple = ()


def _diff(key, other):
    """Позиции, где связки расходятся: [(ось, было, стало), ...]."""
    return [
        (AXIS_NAMES[i], key[i], other[i])
        for i in range(len(AXIS_NAMES))
        if key[i] != other[i]
    ]


def nearest(key, funnels):
    """Ближайшая воронка к связке или None, если расхождение слишком велико.

    «Ближе» = меньше суммарный вес разошедшихся осей, а не их число:
    расхождение по типу воронки почти всегда ошибка разметки, расхождение
    по продукту почти всегда другая воронка. При равном весе выбирается
    меньший номер кода — стабильно между прогонами.
    """
    best = None
    best_rank = None
    for funnel in funnels:
        difference = _diff(key, funnel.key)
        weight = sum(AXIS_WEIGHT[axis] for axis, _, _ in difference)
        if weight > MAX_DIFF_WEIGHT:
            continue
        rank = (weight, _code_num(funnel.label), funnel.label)
        if best_rank is None or rank < best_rank:
            best_rank = rank
            best = Near(funnel=funnel, distance=len(difference),
                        diff=difference)
    return best


def _loose(value):
    """Сравнение имён, набранных руками: схлопывает любые пробелы в один.

    ЧЕСТНО О ЦЕНЕ: сегодня это не меняет НИ ОДНОГО исхода. Замер 03.09.2026
    по всем 68 строкам — замена на обычный `.strip().casefold()` даёт те же
    ступени и те же наборы кандидатов, 0 расхождений. Оба наблюдаемых сорта
    «грязи» безобидны:

      двойной пробел («Яндекс Директ  (холод)», 8 ячеек) стоит по ОБЕ
        стороны — и в таблице, и в `sources.name`, так что сжатие для него
        тавтология;
      табы (11 ячеек в 11 строках, от 18 до 34 штук; у строки 30 их 34) все
        ХВОСТОВЫЕ, и до сравнения не доходят вовсе — `sheet_source._text`
        делает `.strip()` ещё при сборке SheetRow. Внутренних табов в листе
        нет ни одного.

    Оставлено как защита на будущее: таблицу правят руками, и одинарный
    пробел там, где в базе двойной, — вопрос времени. Но это НЕ описание
    поломки, которая есть.
    """
    return ' '.join(str(value or '').split()).casefold()


def match_sheet_row(row, funnels):
    """Строка таблицы -> воронка базы. Три ступени, ступень фиксируется.

    Порядок ступеней отражает надёжность признака:

      landing — физический объект, две воронки не делят один адрес;
      front_code — надёжен там, где проставлен, но проставлен у половины
        строк, а ячейка «Посадочная» местами держит НЕ адрес, а название
        продукта (строка 5: «БЕЗОПАСНОЕ ОЧИЩЕНИЕ ОРГАНИЗМА»). Без этой
        ступени F37 попадала в «строк таблицы без воронки», хотя она есть;
      source_product — последняя попытка; совпадение по ней означает,
        что и лендинг, и код разошлись.

    Третья ступень сверяет колонку таблицы «подрядчик» с `sources.name`, а
    НЕ с `contractors.name`, и это не придирка к именованию. В той колонке
    лежат источники: «ВК NR», «ЮТУБ НИМБ», «Ютуб органика», «Яндекс РСЯ».
    Замер 2026-09-03, 68 строк живой таблицы (13 различных значений) и 78
    воронок; сравнивать надо с тем, что воронки РЕАЛЬНО несут, — ступень
    смотрит на поле воронки, а не в справочник:

      против подрядчиков, которые несут воронки (8 имён) — пересечение
        ноль, 0 совпадений из 68;
      против источников, которые несут воронки (17 имён) — узнаётся 10
        значений из 13, их несут 52 строки из 68.

    Оговорка о справочниках, чтобы никого не ввести в заблуждение: в самой
    таблице `contractors` 11 строк, и одно её значение с таблицей всё же
    совпадает — «ВК БАИНГ». Ступени это не помогало ни разу: этого
    подрядчика не несёт НИ ОДНА воронка (то же самое намерил Phase 17,
    когда убирал ложную занятость справочных значений). То есть ноль был
    структурным, а не редкой невезухой.

    Ступень при этом слабая по построению: источник «ВК NR» держат 15
    воронок, «Яндекс РСЯ» — 17, а разводит их колонка «воронка», в которой
    свободное название, совпадающее с `products.name` лишь у 6 значений из
    49. Поэтому НЕОДНОЗНАЧНОСТЬ ЗДЕСЬ — ОТКАЗ, а не выбор первого по
    порядку: пар (источник, продукт) в базе 68 и семь из них неуникальны
    («ВК NR + ДБО» → f11, f15, f64, f86). Порядок обхода — порядок
    `funnels.id`, то есть произвольный, но УСТОЙЧИВЫЙ: неверная воронка
    выглядела бы авторитетно и воспроизводимо, а дальше по коду становилась
    бы утверждением о её статусе и лендингах.

    Отказ при этом не молчит: кандидаты уезжают в `SheetMatch.candidates` и
    попадают отдельным разделом отчёта. Просто оставить строку в «без
    воронки» было бы неверно вдвойне — раздел утверждал бы, что воронки
    нет, хотя их четыре, и вдобавок он показывает только ЖИВЫЕ строки
    (замер 03.09: из 13 несошедшихся строк живых ноль — 11 «Стоп» и 2 без
    статуса), так что отказ читался бы как «расхождений нет».

    Замер после правки: ступень срабатывает на строках 25-27 → f16, и это
    верно — в таблице лендинги `t.ksamata.ru/nr/boo/{a,b,c}`, а база держит
    у f16 только `/d`. Ровно то расхождение, ради которого ступень и есть.
    """
    if row.landings:
        wanted = set(row.landings)
        for funnel in funnels:
            if wanted & set(funnel.landings):
                return SheetMatch(funnel=funnel, tier='landing')

    if row.front_code:
        for funnel in funnels:
            if funnel.front_code and funnel.front_code == row.front_code:
                return SheetMatch(funnel=funnel, tier='front_code')

    source = _loose(row.contractor)
    product = _loose(row.funnel)
    if source and product:
        candidates = [funnel for funnel in funnels
                      if _loose(funnel.source) == source
                      and _loose(funnel.product) == product]
        if len(candidates) == 1:
            return SheetMatch(funnel=candidates[0], tier='source_product')
        if candidates:
            return SheetMatch(funnel=None, tier=None,
                              candidates=tuple(candidates))

    return SheetMatch(funnel=None, tier=None)
