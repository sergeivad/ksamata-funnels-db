"""Предохранитель: Python не ведёт теги воронок.

`funnel_tags` — это МАТЕРИАЛИЗОВАННЫЙ результат двух слоёв (глобальный шаблон
`tag_templates` плюс пер-воронковые дельты `funnel_tag_overrides`), который
считает `computeTagSet` в приложении. Запись туда сырым SQL живёт ровно до
первого пересчёта: любое сохранение воронки в админке, правка шаблона на `/tags`
или `resyncAllFunnels` перезапишут таблицу из двух слоёв, и всё, что вписал
скрипт, исчезнет без следа и без ошибки.

Поэтому попытка писать теги из Python — это отказ, а не предупреждение:
предупреждение в консоли скроллится и теряется, а данные уходят молча.

Флаг-побег оставлен по образцу `ksamata_funnels_db.py --force`: бывает разовая
починка, когда админка недоступна. Он именно неудобный — чтобы не стал
привычкой.
"""

FORCE_FLAG = '--force-tags'

_MESSAGE = (
    'Отказ: {script} пытается писать в funnel_tags напрямую.\n'
    '\n'
    'funnel_tags — результат вычисления (шаблон + оверрайды), а не хранилище.\n'
    'Первый же пересчёт в админке — сохранение воронки, правка шаблона на /tags\n'
    'или resyncAllFunnels — сотрёт эти строки молча.\n'
    '\n'
    'Как надо: заводить и править воронки через админку или API\n'
    '(createFunnel/updateFunnel), а пер-воронковые отличия — через\n'
    'funnel_tag_overrides.\n'
    '\n'
    f'Если это осознанная разовая починка — запустите с {FORCE_FLAG}.'
)


def guard_tag_write(script, argv=None, force=None):
    """Останавливает скрипт, если он собрался писать теги.

    `force=True` (или {flag} в argv) пропускает запись дальше.
    """.replace('{flag}', FORCE_FLAG)
    if force is None:
        force = FORCE_FLAG in (argv or [])
    if force:
        return
    raise SystemExit(_MESSAGE.format(script=script))
