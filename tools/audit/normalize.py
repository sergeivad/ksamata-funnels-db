#!/usr/bin/env python3
"""Нормализация тегов и разбор АВ-таксономии.

Чистые функции без ввода-вывода: всё остальное в tools/audit строится на них.
"""

import unicodedata

# Четыре оси, образующие ключ склейки предложения с воронкой.
# Порядок значим: он определяет порядок элементов в av_key().
AXES = ('АВ Продукт', 'АВ Подрядчик', 'АВ Канал', 'АВ Направление')

STAGE_PREFIX = 'АВ Этап'
TIME_PREFIX = 'АВ Время'

AUTOFUNNEL_TAG = 'АВ Автоворонка'
LEGACY_AUTOFUNNEL_TAG = 'автоворонки'

# Тип воронки в GetCourse размечается ОДНИМ из четырёх взаимоисключающих
# маркеров, а не только «АВ Автоворонка». «Прямые», «Квиз» и «Квиз-Лайт» —
# это альтернативы, а не отсутствие разметки.
#
# Сверено с реестром 2026-07-25 (7681 предложение): 2192 несут «Автоворонка»,
# 55 — «Прямые», 18 — «Квиз», 12 — «Квиз-Лайт», и ни одно не несёт двух сразу.
#
# Два класса обязаны знать про весь набор:
#   класс 12 — находка только у предложения БЕЗ ЛЮБОГО из маркеров. Проверка
#     на один «Автоворонка» давала 85 ложных срабатываний из 88;
#   класс 11 — маркеры нельзя принимать за оси. Двоеточия в них нет, поэтому
#     разбор «часть до двоеточия» выдаёт весь тег за имя новой оси, и три
#     маркера попадали в отчёт как неизвестные базе оси.
#
# С 2026-07-28 база умеет выражать все четыре: пятая ось (`funnels.funnel_type_id`
# + справочник `funnel_types`) хранит маркер этой воронки, и движок тегов
# материализует его в funnel_tags наравне с осями — вместо жёсткого
# «АВ Автоворонка» в tag_templates (см. docs/superpowers/specs/
# 2026-07-28-funnel-type-fifth-axis-design.md).
MARKER_TAGS = frozenset({
    AUTOFUNNEL_TAG,
    'АВ Прямые',
    'АВ Квиз',
    'АВ Квиз-Лайт',
})

# Теги, которые сознательно живут ТОЛЬКО в GetCourse. База их не хранит и хранить
# не должна, поэтому «база их не знает» — норма, а не находка. Разобрано 2026-07-26.
#
# «АВ Мессенджер: МАКС / ВК / ТГ» — свойство ЗАКАЗА, а не воронки: из 37 четвёрок,
#   у которых есть предложения с мессенджером, 36 несут все три значения сразу
#   (одна воронка порождает заказы во всех трёх мессенджерах). Различать воронки
#   между собой этот тег не может, поэтому осью не является. Сам этап база знает
#   как сценарий `messenger`, и этого достаточно.
# «АВ Линейка: ЖИВО» — надстройка для отчётов GetCourse поверх продуктов `ЖИВО*`.
#   Полностью выводится из продукта (все 26 помеченных предложений имеют продукт
#   `ЖИВО*`), так что в базе была бы вторым источником правды, способным разойтись.
#
# Классы 11 и 2 обязаны их пропускать, иначе они висят в отчёте вечно и топят
# настоящие расхождения.
EXTERNAL_TAG_PREFIXES = ('АВ Мессенджер:', 'АВ Линейка:')

# То же самое, но конкретными значениями, а не префиксом: у оси `АВ Время`
# 15 и 19 — основа модели базы, и выключить её целиком нельзя.
#
# «АВ Время: 17» — решение владельца 2026-07-27. Тег стоял на 22 предложениях
#   трёх ЖИВЫХ воронок (f21, f22, f37) как единственное время, хотя вебинары
#   идут в 15 и 19: за всю историю с ним пришло 12 заказов против 1539 на 19 и
#   1216 на 15 у одной только f22. Владелец добавил этим предложениям
#   `АВ Время: 15`, а 17 ОСТАВИЛ — на нём завязаны внутренние дашборды
#   GetCourse. То есть это отчётный тег, а не слот вебинара: база его не
#   хранит и хранить не должна, чинить нечего.
#
# Осознанно НЕ включено сюда «АВ Время: 20»: решения по нему не было. Все 11
# предложений с ним — на отставленной связке `СВС / Алексей / Яндекс / Квиз`,
# и их гасит фильтр отставки. Оживёт связка — тег вернётся в отчёт, как и
# должен.
#
# Границы фильтра: он выключает теги только там, где вопрос звучит «база
# этого не знает» (классы 2 и 11). `classify` его НЕ трогает, поэтому
# предложение, у которого 17 осталось ЕДИНСТВЕННЫМ временем, по-прежнему
# попадает в класс 5 как оплата без выводимого времени — на 2026-07-27 таких
# четыре (4089235, 4089250, 4089289, 4089485 у f37).
EXTERNAL_TAGS = frozenset({'АВ Время: 17'})


def is_external_tag(tag):
    """Тег живёт только в GetCourse — базе он не нужен.

    Два списка: EXTERNAL_TAG_PREFIXES (вся ось) и EXTERNAL_TAGS (значения).
    """
    return tag in EXTERNAL_TAGS or tag.startswith(EXTERNAL_TAG_PREFIXES)


# Словарь АВ-таксономии: четыре оси, этап, время и маркеры типа воронки.
# Всё остальное в колонке «Теги предложений» — маркетинговая разметка
# GetCourse (`ОТО`, `big-course`, `допродажи`, названия лендов, продуктовые
# слова). База воронок её не хранит, поэтому расходиться там нечему.
#
# Прямое следствие: `АВ Мессенджер:` и `АВ Линейка:` (EXTERNAL_TAG_PREFIXES)
# сюда НЕ попадают, хотя начинаются с «АВ » — они не оси и не этапы. Как и
# легаси-тег «АВ / Мессенджер», вычищенный из GetCourse в июле 2026.
AV_TAG_PREFIXES = tuple(axis + ':' for axis in AXES) + (
    STAGE_PREFIX + ':',
    TIME_PREFIX + ':',
)


def is_av_tag(tag):
    """Тег принадлежит словарю АВ-таксономии: ось, этап, время или маркер типа."""
    return tag in MARKER_TAGS or tag.startswith(AV_TAG_PREFIXES)

# Точное написание, сверено с живой выгрузкой: всё кириллицей.
PREDPISOK_STAGE = 'АВ Этап: Предписок'

STAGE_REG = 'АВ Этап: Регистрация'
STAGE_MESSENGER = 'АВ Этап: Мессенджер'
STAGE_PAYMENT = 'АВ Этап: Оплата'

TIME_19 = 'АВ Время: 19'
TIME_15 = 'АВ Время: 15'

# Легаси-словарь этапа: разметка, которой пользовались до АВ-таксономии.
# Наблюдение с таким тегом и БЕЗ `АВ Этап:` — шаг воронки, продающей мимо
# АВ-разметки, то есть невидимой для всего остального отчёта. Это единственное,
# что отличает такое наблюдение от запуска или клуба: у тех этапа нет вовсе
# (см. legacy_stage_of и класс 5 в findings.find_unresolved).
#
# Замер `deal_export_2026-07-18` (99 928 наблюдений, 2026-07-30): среди 13 455
# наблюдений без АВ-этапа `Регистрация` несут 1618 в 12 наборах, а `Оплата` —
# НИ ОДНОГО. Тег всё равно здесь: словарь описывает легаси-этап как понятие, и
# его отсутствие в данных — факт про сегодняшние выгрузки, а не про правило.
# Появится легаси-оплата — она попадёт в отчёт, а не провалится молча.
LEGACY_STAGE_TAGS = frozenset({'Регистрация', 'Оплата'})

TAG_SEPARATOR = '|'


def normalize_tag(raw):
    """NFC + trim + схлопывание внутренних пробелов. Регистр НЕ трогаем."""
    if raw is None:
        return ''
    text = unicodedata.normalize('NFC', str(raw))
    return ' '.join(text.split())


def parse_tagset(raw):
    """Разбирает значение колонки «Теги предложений» в множество тегов."""
    if raw is None:
        return frozenset()
    parts = (normalize_tag(p) for p in str(raw).split(TAG_SEPARATOR))
    return frozenset(p for p in parts if p)


def fold(tag):
    """Регистронезависимая форма — ТОЛЬКО для сравнения, не для вывода."""
    return normalize_tag(tag).casefold()


def av_value(tags, axis):
    """Значение оси, например av_value(tags, 'АВ Продукт') -> 'ДБО'.

    `tags` — frozenset, порядок обхода которого недетерминирован между
    процессами (рандомизация хеша строк). Если набору соответствует
    несколько тегов одной оси (конфликт, например одновременно
    'АВ Продукт: ДБО' и 'АВ Продукт: ЖКТ'), выбирается лексикографически
    наименьшее значение — стабильно независимо от PYTHONHASHSEED. Сам факт
    конфликта эта функция не сигнализирует и не проверяет.
    """
    prefix = axis + ':'
    values = sorted(
        value
        for tag in tags
        if tag.startswith(prefix)
        for value in (normalize_tag(tag[len(prefix):]),)
        if value
    )
    return values[0] if values else None


def marker_of(tags):
    """Маркер типа воронки. Их четыре и они взаимоисключающие: ни одно
    предложение реестра не несёт двух (сверено 2026-07-28)."""
    found = MARKER_TAGS & {normalize_tag(t) for t in tags}
    return next(iter(found)) if len(found) == 1 else None


def legacy_stage_of(tags):
    """Легаси-маркер этапа набора: 'Регистрация' / 'Оплата' / None.

    Про АВ-этап не знает ничего: сочетание «легаси-этап есть, АВ-этапа нет»
    собирает вызывающий (classify вернёт для такого набора reason='no_stage').

    Если набор несёт оба легаси-этапа сразу, выбирается лексикографически
    наименьший — как в av_value, чтобы результат не зависел от порядка обхода
    frozenset (рандомизация хеша строк между процессами).
    """
    found = LEGACY_STAGE_TAGS & {normalize_tag(t) for t in tags}
    return sorted(found)[0] if found else None


def av_key(tags):
    """АВ-пятёрка: четыре оси в порядке AXES плюс маркер типа воронки.

    Пятый элемент добавлен 2026-07-28: маркер различает РАЗНЫЕ воронки
    с одинаковой четвёркой (f33 и f43 — автоворонка и квиз на одних осях).
    Отсутствующая часть (ось или маркер) даёт None.
    """
    return tuple(av_value(tags, axis) for axis in AXES) + (marker_of(tags),)


def quad(key):
    """Первые четыре элемента ключа — связка (Продукт/Подрядчик/Канал/
    Направление) без типа воронки.

    Нужен везде, где вопрос задаётся о СВЯЗКЕ, а не о конкретной воронке:
    отставка (retired.RETIRED_KEYS хранит связки, а не полные ключи), даты
    последних заказов по связке и класс 10 («неполная четвёрка» — это про
    оси, а не про маркер, у которого свой класс 12). Именованная функция,
    а не срез key[:4] по месту использования: срез в чужом файле однажды
    разойдётся с этим смыслом молча, а самая дорогая ошибка задачи — вызвать
    is_retired с ПОЛНЫМ пятиэлементным ключом (см. retired.py).
    """
    return key[:4]


def is_complete_quad(key):
    """Все четыре оси связки присутствуют — независимо от маркера."""
    return all(part is not None for part in quad(key))


def is_complete_key(key):
    """Ключ полон целиком: все четыре оси И маркер типа воронки.

    Строже, чем is_complete_quad. Если маркера нет (ось не размечена или их
    несколько сразу — см. marker_of), ключ ПОЛНОЙ ВОРОНКИ считается неполным,
    даже когда связка (quad) сама по себе цела."""
    return all(part is not None for part in key)


def key_label(key):
    """Читаемая форма ключа для отчёта; пропуски помечаются тире."""
    return ' / '.join(part if part is not None else '—' for part in key)


def classify(tags):
    """Определяет tag_type по этапу и времени.

    Возвращает (tag_type, reason). Ровно одно из двух не None:
      - ('reg' | 'messenger' | 'time_19' | 'time_15', None) — тип выведен;
      - (None, 'no_stage' | 'predpisok' | 'no_time') — почему не выведен.
    """
    if STAGE_REG in tags:
        return 'reg', None
    if STAGE_MESSENGER in tags:
        return 'messenger', None
    if PREDPISOK_STAGE in tags:
        return None, 'predpisok'
    if STAGE_PAYMENT in tags:
        if TIME_19 in tags:
            return 'time_19', None
        if TIME_15 in tags:
            return 'time_15', None
        return None, 'no_time'
    return None, 'no_stage'
