def is_retired(key, last_order_date=None):
    """Четвёрка отставлена И с тех пор ничего не продала.

    `last_order_date` — дата последнего заказа по этой четвёрке, ISO-строка
    вида `2026-06-15` (хвост после даты игнорируется) или None, если заказов
    нет. Заказ ПОЗЖЕ даты решения отменяет отставку: связка снова работает,
    и находка обязана вернуться в отчёт.

    Дату можно не передавать там, где отсутствие заказов уже установлено —
    класс 14 по своему определению срабатывает только на нуле заказов.

    Дата в непонятном формате трактуется как «заказ был позже» — то есть
    отставка снимается. Fail-open здесь намеренный: лучше лишняя находка
    в отчёте, чем молча спрятанная живая связка.
    """
    entry = RETIRED_KEYS.get(key)
    if entry is None:
        return False
    if last_order_date is None:
        return True
    text = str(last_order_date).strip()
    if not _ISO_DATE.match(text):
        return False
    retired_on, _reason = entry
    return text[:10] <= retired_on
