/**
 * Опознание ботов, которые рисуют карточку предпросмотра ссылки.
 *
 * Мессенджер, увидев в сообщении ссылку, идёт по ней своим ботом и
 * разворачивает её в карточку: заголовок, описание, домен. Для внутренней базы
 * воронок это лишнее — ссылку кидают коллеге в переписке, и рядом с ней
 * каждый раз распускается блок с названием и описанием сервиса. Решение
 * владельца: ссылка приходит голой строкой.
 *
 * `robots.txt` тут не помогает. У сервиса стоит `Disallow: /`
 * ([app/src/app/robots.ts](../app/robots.ts)) и `X-Robots-Tag` на каждом
 * ответе — и превью всё равно рисуется: боты предпросмотра ходят не как
 * поисковый краулер и robots.txt не спрашивают. Убрать мета-описание тоже
 * мало: карточка останется, просто пустее. Единственный рычаг — ответ,
 * который бот получит.
 *
 * Опознаём по `User-Agent`. Подделывается он одной строкой в curl, но это и не
 * защита: задача косметическая, а страницы за этим ответом и так читаются
 * анонимно. Никакого решения о доступе отсюда не следует.
 */

/**
 * Подстроки `User-Agent` (в нижнем регистре) ботов предпросмотра.
 *
 * Telegram ходит как `TelegramBot (like TwitterBot)` — то есть двумя строками
 * сразу; остальные площадки перечислены, потому что владелец попросил гасить
 * превью везде, а не только в телеграме.
 */
const PREVIEW_BOT_MARKERS = [
  'telegrambot',
  'twitterbot',
  'whatsapp',
  'vkshare',
  'slackbot',
  'discordbot',
  'facebookexternalhit',
  'skypeuripreview',
  'viberurldownloader',
  'linkedinbot',
] as const;

export function isLinkPreviewBot(userAgent: string | null | undefined): boolean {
  if (!userAgent) return false;
  const ua = userAgent.toLowerCase();
  return PREVIEW_BOT_MARKERS.some((marker) => ua.includes(marker));
}
