/**
 * F-код воронки («f70») — единственный человеческий номер воронки.
 *
 * С 2026-08-04 код назначает эта база — следующий свободный номер выше
 * максимума (см. docs/leak-engine.md), а ЛИК его принимает: воронка заводится
 * здесь и переносится в ЛИК под тем же кодом. Подставленный код остаётся
 * редактируемым: ЛИК может уже держать более высокий номер — вписали его
 * руками.
 *
 * `funnels.num` — внутренний ключ, с F не связан и человеку не показывается:
 * на 2026-07-28 они совпадали у 16 воронок из 72. Пока черновик получал
 * `frontCode = f${num}`, это ломалось дважды. Во-первых, номер брался не из той
 * последовательности: при max(num)=75 и max(F)=79 следующие два черновика
 * получили бы f76 и f77 — а f77 уже занят живой воронкой. Во-вторых, у
 * `front_code` не было ни уникальности, ни проверки, так что дубль проходил
 * молча. Отсюда правило: следующий код считается от максимума F, а не от num.
 *
 * Модуль намеренно чистый (без обращений к БД) — так его видит и клиентский
 * бандл, и тесты, а запрос к таблице делает вызывающий (см. funnels.ts).
 */

/** Канонический вид кода. Пустая строка — «кода нет», это допустимо. */
export const FRONT_CODE_RE = /^f(\d+)$/;

/**
 * « F70 » → «f70». Разный регистр не был бы просто косметикой: SQLite
 * сравнивает TEXT побайтно, и без приведения «F80» и «f80» разошлись бы в две
 * строки мимо уникального индекса.
 */
export function normalizeFrontCode(raw: string): string {
  return raw.trim().toLowerCase();
}

/**
 * Номер из кода: 'f70' → 70. Пустой или непонятный код → null.
 * Небезопасно большое число тоже null: иначе `nextFrontCode` унесло бы
 * в 1e21, откуда осмысленный код уже не вернуть.
 */
export function frontCodeNum(frontCode: string): number | null {
  const m = FRONT_CODE_RE.exec(normalizeFrontCode(frontCode));
  if (!m) return null;
  const n = Number(m[1]);
  return Number.isSafeInteger(n) ? n : null;
}

/**
 * Следующий свободный код — на единицу выше максимального известного F.
 * Правило владельца от 2026-07-27: воронки нет в ЛИК → код берём ВЫШЕ
 * максимального, потом воронка заводится в ЛИК под ним же. Поэтому именно
 * max+1, а не первая дыра в нумерации: дыры (f10, f14, f17, f18, f20, f44,
 * f49) — это чужие номера, которые ЛИК может выдать в любой момент.
 */
/**
 * Чем подписать ссылку на воронку там, где места на имя нет (чипы мониторинга).
 * Без кода показываем `#id` — тот самый id, что стоит в ссылке `/funnels/<id>`,
 * а не `num`: `num` выглядит как номер F, но им не является.
 */
export function funnelRefLabel(ref: { frontCode: string; id: number }): string {
  return ref.frontCode || `#${ref.id}`;
}

export function nextFrontCode(existing: Iterable<string>): string {
  let max = 0;
  for (const code of existing) {
    const n = frontCodeNum(code ?? '');
    if (n !== null && n > max) max = n;
  }
  return `f${max + 1}`;
}

/**
 * Что стоит в адресе карточки. Две формы, и только две: F-код — канон,
 * числовой id — вечный запасной вход для старых ссылок.
 *
 * Различение по букве, а не по эвристике: `f37` — код, `37` — id. Без этого
 * адрес был бы двусмысленным, а совпадение кода с чужим id — обычное дело
 * (у F37 id равен 1, а id 37 принадлежит другой воронке — f29).
 */
export type FunnelRef =
  | { kind: 'code'; code: string }
  | { kind: 'id'; id: number };

/**
 * Разбор сегмента адреса. `null` — 404: список форм закрытый, новая форма
 * должна появляться здесь явно, а не проскакивать как «похоже на число».
 *
 * Ветка для цифр строже, чем `parseRouteId` из validation.ts (тот отвечает
 * за API, этот — за страницу), и это осознанно, не расхождение по
 * недосмотру: здесь сегмент сначала `trim()`-ится, поэтому « 37 » всё ещё
 * разбирается как id 37, тогда как `parseRouteId` такое отвергнет целиком
 * (его якорный `/^\d+$/` не проходит пробелы). И здесь число проверяется
 * `Number.isSafeInteger`, поэтому чрезмерно длинная цифровая строка даёт
 * `null`, а не число, молча округлённое до ближайшего представимого — чего
 * `parseRouteId` не делает вовсе. Подтягивать `parseRouteId` к этой строгости
 * нельзя: это изменило бы поведение API ради красоты сравнения.
 */
export function parseFunnelRef(raw: string): FunnelRef | null {
  const s = raw.trim();
  if (/^[Ff]\d+$/.test(s)) return { kind: 'code', code: normalizeFrontCode(s) };
  if (/^\d+$/.test(s)) {
    const id = Number(s);
    return Number.isSafeInteger(id) ? { kind: 'id', id } : null;
  }
  return null;
}

/**
 * Сегмент адреса без префикса `/funnels/` — то же правило, что у
 * `funnelHref` и `funnelRefLabel`: есть код — код, нет — id. Вынесен
 * отдельно, чтобы страница карточки (`app/funnels/[ref]/page.tsx`) могла
 * сравнить уже полученный из URL сегмент с каноном, не реконструируя сам
 * путь `/funnels/...` — иначе сторож `funnel-href-consistency.test.ts`
 * ловил бы и эту страницу как ещё одно место ручной сборки ссылки.
 *
 * Код проверяется против `FRONT_CODE_RE`, а не просто на пустоту: домен
 * (`normalizeFrontCode`) код только приводит к нижнему регистру, а форму
 * `^f\d+$` проверяет исключительно Zod на границе API. Разовый tsx-скрипт
 * может записать в базу что-то вроде `'f 86'` мимо этой границы, и такой код
 * не разбирает обратно `parseFunnelRef` — воронка тогда стала бы недостижима
 * ОБОИМИ адресами: канон уходил бы на кривой сегмент, а числовой id
 * редиректил бы на тот же кривой канон. Откат на `String(id)` держит хотя бы
 * числовой адрес рабочим для такой записи.
 */
export function funnelRefSegment(ref: { frontCode: string; id: number }): string {
  return FRONT_CODE_RE.test(ref.frontCode) ? ref.frontCode : String(ref.id);
}

/**
 * Единственное место, где строится ссылка на карточку. До этого она
 * собиралась руками в пяти местах — ровно поэтому и разъезжалась.
 * Правило то же, что у `funnelRefLabel`: есть код — по коду, нет — по id.
 */
export function funnelHref(ref: { frontCode: string; id: number }): string {
  return `/funnels/${funnelRefSegment(ref)}`;
}
