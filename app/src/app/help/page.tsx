/* ── Скриншоты с выносками ──────────────────────────────────────────────── */

interface Marker {
  /** Номер выноски: он же порядковый номер подписи под снимком. */
  n: number;
  /** Позиция в процентах от размера снимка — чтобы кружок ехал вместе с ним. */
  x: number;
  y: number;
  text: string;
}

/**
 * Снимок экрана с пронумерованными выносками.
 *
 * Номера рисуются поверх картинки в HTML, а не вжигаются в неё: подписи
 * правятся текстом, ищутся поиском по странице и попадают в скринридер.
 * Координаты — в процентах, поэтому кружки не разъезжаются при любой ширине.
 *
 * `width`/`height` — настоящий размер файла (снимки сняты на 2× экране).
 * Без них страница дёргается при загрузке картинок.
 */
function Shot({
  src,
  alt,
  width,
  height,
  markers = [],
  note,
}: {
  src: string;
  alt: string;
  width: number;
  height: number;
  markers?: Marker[];
  note?: string;
}) {
  return (
    <figure className="mb-4">
      <div className="relative overflow-hidden rounded-[10px] border border-[var(--line-soft)] bg-[var(--card)]">
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={src} alt={alt} width={width} height={height} className="block h-auto w-full" />
        {markers.map((m) => (
          <span
            key={m.n}
            aria-hidden
            style={{ left: `${m.x}%`, top: `${m.y}%` }}
            className="absolute -translate-x-1/2 -translate-y-1/2 grid h-[22px] w-[22px] place-items-center rounded-full bg-[var(--orange)] text-[12px] font-bold text-white shadow-[0_0_0_2px_rgba(255,255,255,0.9)]"
          >
            {m.n}
          </span>
        ))}
      </div>
      {markers.length > 0 && (
        <figcaption className="mt-2">
          <ol className="flex flex-col gap-1">
            {markers.map((m) => (
              <li key={m.n} className="flex gap-2 text-[12.5px] leading-snug text-[var(--muted)]">
                <span className="mt-[1px] grid h-[17px] w-[17px] shrink-0 place-items-center rounded-full bg-[var(--orange)] text-[10px] font-bold text-white">
                  {m.n}
                </span>
                <span>{m.text}</span>
              </li>
            ))}
          </ol>
          {note && <p className="mt-1.5 text-[11.5px] text-[var(--faint)]">{note}</p>}
        </figcaption>
      )}
    </figure>
  );
}

/* ── Примитивы вёрстки ──────────────────────────────────────────────────── */

function Section({
  id,
  title,
  children,
}: {
  id: string;
  title: string;
  children: React.ReactNode;
}) {
  return (
    <section id={id} className="mt-10 scroll-mt-20">
      <h2 className="border-b border-[var(--line-soft)] pb-1.5 text-[17px] font-semibold text-[var(--ink)]">
        {title}
      </h2>
      <div className="mt-3">{children}</div>
    </section>
  );
}

function Sub({ children }: { children: React.ReactNode }) {
  return (
    <h3 className="mb-1.5 mt-5 text-[14px] font-semibold text-[var(--ink)]">
      {children}
    </h3>
  );
}

function P({ children }: { children: React.ReactNode }) {
  return (
    <p className="mb-2.5 text-[13.5px] leading-relaxed text-[var(--muted)]">
      {children}
    </p>
  );
}

function B({ children }: { children: React.ReactNode }) {
  return <strong className="font-semibold text-[var(--ink)]">{children}</strong>;
}

function Code({ children }: { children: React.ReactNode }) {
  return (
    <code className="rounded-[4px] bg-[var(--chip)] px-1 py-[1px] font-mono text-[12px] text-[var(--ink)]">
      {children}
    </code>
  );
}

function List({ children }: { children: React.ReactNode }) {
  return (
    <ul className="mb-2.5 flex list-disc flex-col gap-1.5 pl-5 text-[13.5px] leading-relaxed text-[var(--muted)] marker:text-[var(--faint)]">
      {children}
    </ul>
  );
}

function Steps({ children }: { children: React.ReactNode }) {
  return (
    <ol className="mb-2.5 flex list-decimal flex-col gap-2 pl-5 text-[13.5px] leading-relaxed text-[var(--muted)] marker:font-semibold marker:text-[var(--orange)]">
      {children}
    </ol>
  );
}

/** Пояснение: полезно знать, но ничего не сломается. */
function Note({ children }: { children: React.ReactNode }) {
  return (
    <div className="mb-2.5 rounded-[10px] border border-[var(--line-soft)] bg-[var(--card)] px-3.5 py-2.5 text-[13px] leading-relaxed text-[var(--muted)]">
      {children}
    </div>
  );
}

/** Предупреждение: здесь можно испортить данные. */
function Warn({ children }: { children: React.ReactNode }) {
  return (
    <div className="mb-2.5 rounded-[10px] border border-[var(--orange)] bg-[var(--orange-soft)] px-3.5 py-2.5 text-[13px] leading-relaxed text-[var(--muted)]">
      {children}
    </div>
  );
}

function Table({ head, rows }: { head: string[]; rows: string[][] }) {
  return (
    // Таблица уезжает по горизонтали внутри своей обёртки, а не тянет вбок всю
    // страницу — на телефоне колонок всё равно не хватает.
    <div className="mb-3 overflow-x-auto">
      <table className="w-full min-w-[420px] border-collapse text-[13px]">
        <thead>
          <tr>
            {head.map((h, i) => (
              <th
                key={i}
                className="border-b border-[var(--line)] px-2 py-1.5 text-left text-[10px] uppercase tracking-wide text-[var(--faint)]"
              >
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={i}>
              {r.map((c, j) => (
                <td
                  key={j}
                  className={`border-b border-[var(--line-soft)] px-2 py-1.5 align-top ${
                    j === 0 ? 'font-medium text-[var(--ink)]' : 'text-[var(--muted)]'
                  }`}
                >
                  {c}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
