/**
 * Копия реальной БД для тестовой фикстуры.
 *
 * `copyFileSync` копирует только главный файл. Записи, которые SQLite держит в
 * `*.db-wal` (а при работающем дев-сервере они там всегда), в копию не попадают;
 * хуже того, копирование файла, в который параллельно чекпоинтит другой процесс,
 * может дать вообще несогласованный снимок — тесты начинают то падать, то
 * проходить на фантомных данных.
 *
 * `VACUUM INTO` отдаёт согласованный снимок независимо от состояния WAL и,
 * в отличие от асинхронного `db.backup()`, синхронен — а фикстуры строятся на
 * верхнем уровне модуля теста. Для исходной БД операция read-only.
 */
import Database from 'better-sqlite3';

export function copyDbForTest(source: string, dest: string): void {
  const src = new Database(source, { readonly: true });
  try {
    src.exec(`VACUUM INTO '${dest.replace(/'/g, "''")}'`);
  } finally {
    src.close();
  }
}
