/**
 * Phase-17: осевые FK-колонки следуют за тегами.
 * Идемпотентна.
 *
 *   cd app/
 *   npx tsx scripts/migrate-phase17-runner.ts
 *
 * Запускается только через свой раннер — он единственная точка входа и в
 * Docker, и вручную. Своего CLI-блока у файла нет сознательно: esbuild
 * бандлит раннер вместе с этим файлом, и внутри бандла
 * `require.main === module` истинно, так что блок сработал бы на импорте
 * и миграция выполнялась бы дважды за старт контейнера.
 *
 * ─── Что чинится ───────────────────────────────────────────────────────────
 *
 * `funnels.contractor_id` и `funnels.product_id` — кэш осей, а не сами оси.
 * Источник истины по осям — `funnel_tags` (CLAUDE.md, раздел про теги), и
 * карточка воронки читает их именно оттуда (`getAxesForFunnel`). Колонки же
 * пишутся отдельно и с тех пор ни разу не сверялись.
 *
 * Замер 02.09.2026 по репозиторной базе (77 воронок): `product_id` сходится
 * везде, `contractor_id` разошёлся на семи —
 *
 *   f36, f37, f38, f81 — колонка «Органика», тег «Внутренний»
 *   f82, f83           — колонка «Перелив»,  тег «Внутренний»
 *   f89                — колонка «FAQ»,      тег «NR»
 *
 * — и это не дрейф, а разовая ошибка импорта: в контракте `add_av_tags.py`
 * кортеж идёт `(продукт, канал, направление, подрядчик)`, у воронки 1 это
 * `('БОО', 'Ютуб', 'Органика', 'Внутренний')`, а `ksamata_funnels_db.py`
 * читает свой кортеж как `(продукт, подрядчик, вариант)` и кладёт ту же
 * строку 1 как `('БОО', 'Органика', 'ЮТУБ')`. То есть в колонку подрядчика
 * уехало НАПРАВЛЕНИЕ; у f82/f83 тем же способом уехал КАНАЛ («Перелив»),
 * его до сих пор жёстко зашивает `add_pereliv_funnels.py`.
 *
 * ─── Чем это мешает ────────────────────────────────────────────────────────
 *
 * 1. `/refs` считает использование справочника по FK-колонке И по зеркальному
 *    тегу (`getRefUsage`), а удалять значение отказывается, пока счёт не ноль.
 *    Поэтому «Органика» (4) и «Перелив» (2) числились занятыми и не
 *    удалялись, хотя подрядчиком их не несёт ни одна воронка. После фазы обе
 *    показывают ноль и удаляются — как «ВК БАИНГ», у которого ноль и сейчас.
 * 2. `tools/data-export` печатает в XLSX «Подрядчик:» из колонки — семь
 *    строк отчёта врали.
 * 3. `tools/reconcile` держит колонку в `Funnel.contractor`.
 *
 * ─── Почему фазой, а не разовым скриптом ───────────────────────────────────
 *
 * Ровно по доводу фаз 10 и 11: колонку продолжает писать Python-импорт, и
 * неверные литералы в нём никуда не делись (`add_pereliv_funnels.py` и
 * сейчас содержит `'contractor': 'Перелив'`). Разовый скрипт починил бы
 * снимок, следующий прогон импорта вернул бы расхождение — и снова молча.
 * Историю импорта при этом не переписываем: скрипты писались под модель
 * своего дня, а фаза чинит результат ЛЮБОГО писателя, не только тех, кого
 * мы бы успели пропатчить.
 *
 * Само по себе расхождение к тому же самоустраняется по одной воронке за
 * раз: `updateFunnel` разрешает присланное ИМЯ оси обратно в FK через
 * `createRef`, так что первое же «Сохранить идентификацию» на карточке тихо
 * чинит её колонку. Это не аргумент отложить, а аргумент закрыть осознанно:
 * пока чинится вразнобой, любой запрос по `contractor_id` даёт разный ответ
 * в разные дни.
 *
 * ─── Почему source_id не трогаем ───────────────────────────────────────────
 *
 * Зеркального тега у `sources` нет, и вывести источник из осей нельзя.
 * `updateFunnel` при СМЕНЕ канала или подрядчика собирает имя источника как
 * `«<канал> <подрядчик>»` — но это правило рождения нового значения, а не
 * определение истины. Замер 02.09.2026: у 49 воронок из 77 имя источника
 * этой склейке не равно, и различия содержательные —
 *
 *   f21–f23 «Яндекс Директ  (холод)» против f24–f26 «Яндекс Директ  (ретаргет)»
 *
 * — при полностью одинаковых осях (Яндекс / Алексей). Холод и ретаргет
 * различает ТОЛЬКО `source_id`; «сверка с тегами» стёрла бы это различие на
 * шести воронках, а заодно свела бы «Ютуб органика», «Сайт СЕО» и «Партнеры»
 * к склейкам. Источник — самостоятельное поле, а не кэш осей, и в этой фазе
 * ему делать нечего.
 *
 * ─── Границы ───────────────────────────────────────────────────────────────
 *
 * Воронка без осевого тега ПРОПУСКАЕТСЯ, а не обнуляется: колонки NOT NULL,
 * и пустой черновик — законное состояние (`createDraftFunnel` берёт первое
 * значение справочника и не проставляет AV-теги, а `resyncAllFunnels` такие
 * черновики сознательно обходит). Обнулять было бы нечем, а выдумывать —
 * нечего.
 *
 * Тег, значения которого нет в справочнике, тоже ПРОПУСКАЕТСЯ: заводить
 * строку справочника фаза не вправе. `createRef` в приложении — get-or-create
 * и работает от живого ввода человека; фаза же завела бы подрядчика из
 * опечатки в теге и разнесла бы её по `/refs` навсегда. Замер 02.09.2026:
 * таких значений ноль, шаг — предохранитель.
 */

import { PHASE17_AXES, type Phase17Axis } from './migrate-phase17-data';

type Sqlite = import('better-sqlite3').Database;

/** Одна починенная воронка — строка отчёта фазы. */
export interface Phase17Fix {
  funnelId: number;
  /** F-код, если проставлен; иначе `#id` — `num` человеку не показываем. */
  label: string;
  /** Какая ось: «подрядчик» / «продукт». */
  axis: string;
  /** Что стояло в колонке (пусто, если строка справочника уже исчезла). */
  from: string;
  /** Что говорит тег. */
  to: string;
}

export interface Phase17Result {
  /** Починенные воронки, по одной строке на ось. */
  fixed: Phase17Fix[];
  /**
   * Воронки, у которых тег есть, а значения нет в справочнике — пропущены.
   * Пусто на здоровой базе; непусто означает расхождение тегов и `/refs`.
   */
  unresolved: Phase17Fix[];
}

/**
 * Расхождения по одной оси.
 *
 * `funnel_tags` берём ТОЛЬКО со сценарием `reg`: оси материализуются во все
 * сценарии одинаково, а `reg` — тот, из которого их читает и приложение
 * (`getAxesForFunnel`). Брать любой сценарий значило бы получить одну и ту
 * же ось четырежды.
 */
function driftFor(sqlite: Sqlite, axis: Phase17Axis): { fixable: Phase17Fix[]; unresolved: Phase17Fix[] } {
  const rows = sqlite
    .prepare(
      `SELECT f.id                                        AS funnelId,
              COALESCE(NULLIF(TRIM(f.front_code), ''), '#' || f.id) AS label,
              COALESCE(ref.name, '')                      AS fromName,
              SUBSTR(t.name, LENGTH(?) + 1)               AS toName,
              (SELECT r.id FROM ${axis.table} r
                WHERE r.name = SUBSTR(t.name, LENGTH(?) + 1)) AS toId
         FROM funnels f
         JOIN funnel_tags ft ON ft.funnel_id = f.id AND ft.tag_type = 'reg'
         JOIN tags t         ON t.id = ft.tag_id AND t.name LIKE ? || '%'
    LEFT JOIN ${axis.table} ref ON ref.id = f.${axis.column}
        WHERE COALESCE(ref.name, '') <> SUBSTR(t.name, LENGTH(?) + 1)
        ORDER BY f.id`
    )
    .all(axis.prefix, axis.prefix, axis.prefix, axis.prefix) as {
    funnelId: number;
    label: string;
    fromName: string;
    toName: string;
    toId: number | null;
  }[];

  const fixable: Phase17Fix[] = [];
  const unresolved: Phase17Fix[] = [];
  for (const row of rows) {
    const entry: Phase17Fix = {
      funnelId: row.funnelId,
      label: row.label,
      axis: axis.label,
      from: row.fromName,
      to: row.toName,
    };
    (row.toId === null ? unresolved : fixable).push(entry);
  }
  return { fixable, unresolved };
}

export function runMigratePhase17(sqlite: Sqlite): Phase17Result {
  sqlite.pragma('foreign_keys = ON');

  const result: Phase17Result = { fixed: [], unresolved: [] };

  // Одной транзакцией: две оси — одно решение о том, чему верить.
  const tx = sqlite.transaction(() => {
    for (const axis of PHASE17_AXES) {
      const { fixable, unresolved } = driftFor(sqlite, axis);
      result.unresolved.push(...unresolved);
      if (fixable.length === 0) continue;

      const update = sqlite.prepare(
        `UPDATE funnels
            SET ${axis.column} = (SELECT r.id FROM ${axis.table} r WHERE r.name = ?)
          WHERE id = ?`
      );
      for (const fix of fixable) update.run(fix.to, fix.funnelId);
      result.fixed.push(...fixable);
    }
  });
  tx();

  return result;
}
