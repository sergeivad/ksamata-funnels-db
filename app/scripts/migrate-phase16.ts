/**
 * Phase-16: предсписок становится свойством воронки, а не частью модели.
 * Идемпотентно.
 *
 *   cd app/
 *   npx tsx scripts/migrate-phase16-runner.ts
 *
 * Запускается только через свой раннер — он единственная точка входа и в
 * Docker, и вручную. Своего CLI-блока у файла нет сознательно: esbuild
 * бандлит раннер вместе с этим файлом, и внутри бандла
 * `require.main === module` истинно, так что блок сработал бы на импорте
 * и миграция выполнялась бы дважды за старт контейнера.
 *
 * Зачем. Фаза 14 завела `predspisok` пятым сценарием и раздала набор ВСЕМ
 * воронкам — сценарий был объявлен частью модели. В реестре предложений
 * GetCourse этап заведён у меньшинства: замер 02.09.2026 — 34 воронки из 78.
 * У остальных 44 база показывала набор, которому в реестре не соответствует
 * ничего, и человек, копируя теги с карточки, размечал ими заказ шага,
 * которого у воронки нет.
 *
 * Признак кладём на ВОРОНКУ, а не на тип, в отличие от фазы 12 — и это замер,
 * а не вкус. Все 34 воронки с предпиской имеют тип «АВ Автоворонка», но 31
 * автоворонка предсписка не имеет; продукт и статус не делят вовсе. Значит
 * тип — условие необходимое, но не достаточное, и свойство принадлежит
 * воронке. Подробнее — docs/superpowers/specs/2026-09-02-predspisok-optional-design.md.
 *
 * Три шага, и второй отличается от третьего условием запуска:
 *
 *  1. Колонка `has_predspisok`, если её ещё нет.
 *  2. Нули у 44 воронок из замера — ТОЛЬКО в прогон, который эту колонку и
 *     завёл. `NOT NULL DEFAULT 1` не отличает «ещё не решали» от «решили, что
 *     предсписок есть», так что безусловный бэкфилл затирал бы галку,
 *     поставленную человеком на карточке, при каждом старте контейнера.
 *     Это дословно грабли фазы 12.
 *  3. Снятие наборов predspisok с воронок без признака — при КАЖДОМ прогоне.
 *
 * Третий шаг правит funnel_tags напрямую, в обход движка шаблонов и
 * оверрайдов, чего обычно делать нельзя. Здесь можно ровно потому, что
 * удаляются те и только те строки, которых движок теперь и не построит:
 * ближайшая материализация даёт тот же результат (проверяется тестом).
 * Безусловность делает шаг самовосстанавливающимся — если набор предсписка
 * когда-нибудь приедет мимо приложения, следующий старт его подметёт.
 *
 * Оверрайды сценария НЕ трогаются: снял галку — набор пропал, вернул — вернулся
 * ровно тот, что был. Хранить их дёшево, восстанавливать руками — нет.
 */
import { addColumnIfMissing } from './migrate-phase3-data';
import { PHASE16_COLUMN, PHASE16_FUNNELS_WITHOUT_PREDSPISOK } from './migrate-phase16-data';
import { PHASE14_SCENARIO } from './migrate-phase14-data';

export interface Phase16Result {
  /** Воронок, помеченных как «без предсписка» (только в прогон, заводящий колонку). */
  funnelsCleared: number;
  /** Снятых строк funnel_tags сценария predspisok. */
  tagRowsRemoved: number;
}

function hasColumn(
  sqlite: import('better-sqlite3').Database,
  table: string,
  column: string,
): boolean {
  return (sqlite.prepare(`PRAGMA table_info(${table})`).all() as { name: string }[])
    .some((r) => r.name === column);
}

export function runMigratePhase16(sqlite: import('better-sqlite3').Database): Phase16Result {
  sqlite.pragma('foreign_keys = ON');

  const columnExisted = hasColumn(sqlite, 'funnels', PHASE16_COLUMN.name);

  let funnelsCleared = 0;
  let tagRowsRemoved = 0;

  sqlite.transaction(() => {
    // Колонка заводится ВНУТРИ транзакции, вместе с бэкфиллом. DDL в SQLite
    // транзакционен, и это здесь не украшение: коммить ALTER отдельно значит
    // сделать «колонка есть» и «бэкфилл выполнен» независимыми фактами. Прогон,
    // умерший между ними (OOM при старте контейнера, убитый деплой), оставил бы
    // колонку без бэкфилла — а следующий старт увидел бы её, СЧЁЛ БЭКФИЛЛ
    // СДЕЛАННЫМ и пропустил бы навсегда. Все воронки остались бы с единицей,
    // третьему шагу нечего сносить, приложение выглядит как до фазы, и никакой
    // ошибки в логах нет. Чинилось бы только сносом колонки вручную — о чём
    // никто не догадается, потому что симптома нет.
    //
    // Фазы 12 и 4 устроены иначе (ALTER снаружи), и это их слабое место, а не
    // образец; идиома «в одной транзакции, перенос первым, чтобы прерванный
    // прогон ничего не потерял» в репозитории уже есть — у фазы 10.
    addColumnIfMissing(sqlite, 'funnels', PHASE16_COLUMN.name, PHASE16_COLUMN.ddl);

    if (!columnExisted) {
      // Сравнение через lower(): фаза 7 привела коды к нижнему регистру, но
      // SQLite сравнивает TEXT побайтово, и занесённый мимо приложения «F81»
      // молча не нашёлся бы. Коды в списке — ASCII, так что lower() честен.
      const clear = sqlite.prepare(
        `UPDATE funnels SET ${PHASE16_COLUMN.name} = 0 WHERE lower(front_code) = ?`,
      );
      for (const code of PHASE16_FUNNELS_WITHOUT_PREDSPISOK) {
        funnelsCleared += clear.run(code.toLowerCase()).changes;
      }
    }

    // Сам тег «АВ Этап: Предсписок» в таблице tags остаётся — он в ходу у 34
    // воронок, у которых предсписок есть; удалять его оттуда нельзя.
    tagRowsRemoved = sqlite
      .prepare(
        `DELETE FROM funnel_tags
          WHERE tag_type = ?
            AND funnel_id IN (SELECT id FROM funnels WHERE ${PHASE16_COLUMN.name} = 0)`,
      )
      .run(PHASE14_SCENARIO).changes;
  })();

  return { funnelsCleared, tagRowsRemoved };
}
